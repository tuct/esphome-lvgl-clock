#!/usr/bin/env bash
#
# Stage the add-on's payload from the single copies in this repo.
#
# Two things have to be produced before `docker build`:
#
#   app/www/sim/            the engine, the wall and the pattern model, which
#                           the add-on's page loads directly
#   app/www/cards/          the same, plus the Lovelace cards - the add-on's
#                           page instantiates the EDITOR CARD itself rather
#                           than reimplementing it
#   app/www/…-card.js       the Lovelace bundle, installed into /config/www at
#                           start so the cards are at /local/
#
# Docker cannot reach outside its build context, so these are COPIES - and
# copies drift. This script is what stops them: run it after changing a mode or
# a card, and never edit anything under app/www by hand.

set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"

SIM="../tools/clockclock24-sim"
OUT="app/www/clockclock24-card.js"
PARTS=("$SIM/engine.js" "$SIM/wall.js" "$SIM/pattern.js" "cards/card.js" "cards/editor-card.js")

for f in "${PARTS[@]}"; do
  [ -f "$f" ] || { echo "missing: $f" >&2; exit 1; }
done

rm -rf app/www
mkdir -p app/www/sim app/www/cards

cp "$SIM"/index.html "$SIM"/engine.js "$SIM"/wall.js "$SIM"/pattern.js app/www/sim/
cp cards/card.js cards/editor-card.js app/www/cards/

# The Lovelace bundle is the same files CONCATENATED, not copied: there is
# exactly one implementation of a choreography in this repo. Change a mode in
# tools/clockclock24-sim and it changes in the firmware port, the project site,
# this add-on and the card together. No npm, no bundler - the sandbox files are
# plain classic scripts that hang everything off window.CC, which is all a
# Lovelace resource needs.
{
  echo "// clockclock24-card - GENERATED by homeassistant/stage.sh"
  echo "// Do not edit. Edit cards/*.js, or the sandbox in tools/clockclock24-sim/, and rebuild."
  echo "// Built from: ${PARTS[*]}"
  echo
  for f in "${PARTS[@]}"; do
    echo "// ─── $(basename "$f") ───────────────────────────────────────────────"
    cat "$f"
    echo
  done
} > "$OUT"

echo "staged:"
echo "  app/www/sim       $(ls app/www/sim | wc -l | tr -d ' ') files"
echo "  app/www/cards     $(ls app/www/cards | wc -l | tr -d ' ') files"
echo "  $OUT  ($(wc -l < "$OUT" | tr -d ' ') lines, $(wc -c < "$OUT" | tr -d ' ') bytes)"
